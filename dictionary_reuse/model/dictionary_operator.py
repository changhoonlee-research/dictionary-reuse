def _top_mass_ratio(abs_coeff: torch.Tensor, coeff_total: float, k: int) -> float:
    top_k = min(int(k), int(abs_coeff.numel()))
    if top_k <= 0:
        return 0.0
    return float(_topk_abs_sum(abs_coeff, top_k).cpu()) / coeff_total


