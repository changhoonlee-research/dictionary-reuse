    # --- Construction --------------------------------------------------------
    @classmethod
    def from_dimensions(
        cls,
        in_features: int,
        out_features: int,
        *,
        bias: bool,
        atom_count: int,
        low_atom_count: int,
        basis_type: str,
        dictionary_mode: str,
        seed: int,
        target_weight_rms: float,
        bias_policy: str = "zero_frozen",
        primitive_spec: Sequence[dict[str, int | str]] | None = None,
        coefficient_quantization_config: dict[str, Any] | None = None,
    ) -> "SeparableDictionaryLinear":
        """Construct without reading a dense random weight RMS.

        Full DiR endpoint/attention runs use this path so the only allowed
        seed-dependent initialization is the DiR coefficient/dictionary state,
        not a discarded dense carrier scale.
        """
        replacement = cls(
            int(in_features),
            int(out_features),
            bias=bool(bias),
            atom_count=atom_count,
            low_atom_count=low_atom_count,
            basis_type=basis_type,
            dictionary_mode=dictionary_mode,
            seed=seed,
            target_weight_rms=float(target_weight_rms),
            bias_policy=bias_policy,
            primitive_spec=primitive_spec,
            coefficient_quantization_config=coefficient_quantization_config,
        )
        replacement._dictionary_construction_source = "from_dimensions"
        replacement._dictionary_uses_dense_rms = False
        return replacement

    @classmethod
    def from_linear(
        cls,
        linear_layer: nn.Linear,
        *,
        atom_count: int,
        low_atom_count: int,
        basis_type: str,
        dictionary_mode: str,
        seed: int,
        bias_policy: str = "zero_frozen",
        primitive_spec: Sequence[dict[str, int | str]] | None = None,
        coefficient_quantization_config: dict[str, Any] | None = None,
    ) -> "SeparableDictionaryLinear":
        with torch.no_grad():
            target_rms = float(linear_layer.weight.detach().float().pow(2).mean().sqrt().clamp_min(1e-8).cpu())
        replacement = cls(
            int(linear_layer.in_features),
            int(linear_layer.out_features),
            bias=linear_layer.bias is not None,
            atom_count=atom_count,
            low_atom_count=low_atom_count,
            basis_type=basis_type,
            dictionary_mode=dictionary_mode,
            seed=seed,
            target_weight_rms=target_rms,
            bias_policy=bias_policy,
            primitive_spec=primitive_spec,
            coefficient_quantization_config=coefficient_quantization_config,
        )
        replacement._dictionary_construction_source = "from_linear"
        replacement._dictionary_uses_dense_rms = True
        if linear_layer.bias is not None and replacement.bias is not None and str(bias_policy).startswith("copy_"):
            with torch.no_grad():
                replacement.bias.copy_(linear_layer.bias.detach())
        return replacement


    # --- Dictionary and coefficient coordinate system ------------------------
    def dictionary_base_rank1_atom_scale(self) -> torch.Tensor:
        """Return the fixed construction-time D scale used before C-RMS absorption."""

        reference = self.coefficient_magnitude
        row_norm = self.row_initial_base.float().norm(dim=0).clamp_min(
            float(self.coefficient_layer_rms_normalization_eps)
        )
        col_norm = self.col_initial_base.float().norm(dim=0).clamp_min(
            float(self.coefficient_layer_rms_normalization_eps)
        )
        rank1_scales = row_norm * col_norm
        return rank1_scales.pow(2).mean().sqrt().to(device=reference.device, dtype=reference.dtype)

    def _row_and_col_atoms(self) -> tuple[torch.Tensor, torch.Tensor]:
        # Optimizer-step projection maintains unit-norm atoms. Returning the
        # parameters directly avoids repeating two full column normalizations
        # in every forward while preserving the represented operator.
        return self.row_atoms, self.col_atoms

    def dictionary_weight(self, coefficient: torch.Tensor | None = None) -> torch.Tensor:
        coeff = self.effective_coefficient(coefficient)
        mode = str(getattr(self, "_coefficient_contract_mode", "none"))
        if mode != "none":
            # Weight-based analysis must see exactly the same endpoint contract
            # as the functional forward. B keeps dropped support at zero, while
            # C force-restores every endpoint-active contribution.
            coeff = self._apply_effective_coefficient_contract(
                coeff, preserve_zero_support=(mode != "frozen")
            )
        row_atoms, col_atoms = self._row_and_col_atoms()
        return torch.einsum("k,ok,ik->oi", coeff, row_atoms, col_atoms)

    def _static_relative_support_mask(self, *, device: torch.device) -> torch.Tensor:
        support = torch.ones(self.atom_count, device=device, dtype=torch.bool)
        if self.coefficient_support_is_committed():
            support = support & self.coefficient_commit_mask.to(device=device, dtype=torch.bool)
        if (
            bool(getattr(self, "forward_routed_gate_enabled", False))
            and bool(getattr(self, "forward_routed_gate_use_copied_hard_support_mask", True))
            and self._forward_routed_fixed_support_is_initialized()
        ):
            support = support & self.forward_routed_fixed_support_mask.to(device=device, dtype=torch.bool)
        # Commit/fixed-support setters enforce nonempty masks. Avoid a CUDA
        # tensor-to-Python boolean conversion in every relative-C forward.
        return support

    def _current_relative_support_mask(self, *, device: torch.device) -> torch.Tensor:
        support = self._static_relative_support_mask(device=device)
        if (
            bool(getattr(self, "forward_routed_gate_enabled", False))
            and self._forward_routed_support_seen
            and not self._forward_routed_fixed_support_is_initialized()
        ):
            support = support & self.forward_routed_previous_support.to(device=device, dtype=torch.bool)
        return support

    def _actual_forward_support_mask_for_metrics(self, *, device: torch.device) -> torch.Tensor:
        route_hard_gate = getattr(self, "_last_forward_routed_hard_gate", None)
        if bool(getattr(self, "_last_forward_routed_gate_enabled", False)) and isinstance(route_hard_gate, torch.Tensor):
            support = route_hard_gate.detach().to(device=device).reshape(-1) >= 0.5
            if int(support.numel()) == int(self.atom_count):
                return support
        return self._current_relative_support_mask(device=device)

    @staticmethod
    def _straight_through_clamp(value: torch.Tensor, *, minimum: float, maximum: float) -> torch.Tensor:
        hard = value.clamp(min=float(minimum), max=float(maximum))
        return value + (hard - value).detach()

    def _bounded_relative_magnitude(self, *, detach: bool = False) -> torch.Tensor:
        magnitude = self._straight_through_clamp(
            self.coefficient_magnitude,
            minimum=float(self.relative_coefficient_min_ratio),
            maximum=float(self.relative_coefficient_max_ratio),
        )
        if self.relative_coefficient_ratio_quantization == "decimal":
            places = max(0, int(getattr(self, "coefficient_quantization_decimal_places", 4)))
            decimal_scale = float(10**places)
            hard = (torch.round(magnitude * decimal_scale) / decimal_scale).clamp(
                min=float(self.relative_coefficient_min_ratio),
                max=float(self.relative_coefficient_max_ratio),
            )
            if bool(getattr(self, "coefficient_quantization_straight_through", True)):
                magnitude = magnitude + (hard - magnitude).detach()
            else:
                magnitude = hard
        return magnitude.detach() if detach else magnitude

    @staticmethod
    def _masked_active_mean(magnitude: torch.Tensor, support: torch.Tensor) -> torch.Tensor:
        support_value = support.to(device=magnitude.device, dtype=magnitude.dtype)
        return (magnitude * support_value).sum() / support_value.sum().clamp_min(1.0)

    def _prepare_relative_coefficient_magnitude(self) -> torch.Tensor:
        """Prepare the direct bounded positive C vector exactly once."""

        return self._bounded_relative_magnitude()

    @staticmethod
    def _paired_masked_active_means(
        magnitude: torch.Tensor,
        old_support: torch.Tensor,
        new_support: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Compute previous/current active means with one stacked reduction."""

        masks = torch.stack((old_support, new_support), dim=0).to(
            device=magnitude.device, dtype=magnitude.dtype
        )
        sums = torch.matmul(masks, magnitude)
        counts = masks.sum(dim=1).clamp_min(1.0)
        means = sums / counts
        return means[0], means[1]

    def _relative_code_from_primitives(
        self,
        *,
        magnitude: torch.Tensor,
        support_mask: torch.Tensor,
        active_mean: torch.Tensor,
    ) -> torch.Tensor:
        support = support_mask.to(device=magnitude.device, dtype=torch.bool)
        relative_magnitude = magnitude / active_mean.clamp_min(float(self.relative_coefficient_epsilon))
        relative_code = relative_magnitude
        self._last_relative_coefficient_active_mean = active_mean.detach()
        record_relative_diagnostics = bool(
            not self.training
            or bool(getattr(self, "_activation_contribution_measurement_enabled", False))
        )
        if record_relative_diagnostics:
            active_relative = relative_magnitude[support]
            active_raw = magnitude[support]
            self._last_relative_coefficient_min = active_relative.amin().detach()
            self._last_relative_coefficient_max = active_relative.amax().detach()
            self._last_relative_coefficient_active_atoms = support.sum().detach()
            self._last_relative_coefficient_raw_min = active_raw.amin().detach()
            self._last_relative_coefficient_raw_max = active_raw.amax().detach()
        return relative_code

    def _relative_coefficient_components(
        self,
        *,
        support_mask: torch.Tensor,
        active_mean_override: torch.Tensor | None = None,
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """Materialize bounded positive C, active mean, and relative code once."""

        support = support_mask.to(device=self.coefficient_magnitude.device, dtype=torch.bool)
        if int(support.numel()) != int(self.atom_count):
            raise RuntimeError("relative-C support must match atom_count")
        magnitude = self._prepare_relative_coefficient_magnitude()
        computed_active_mean = self._masked_active_mean(magnitude, support)
        if active_mean_override is None:
            active_mean = computed_active_mean
        else:
            override = active_mean_override.to(device=magnitude.device, dtype=magnitude.dtype)
            active_mean = computed_active_mean + (override - computed_active_mean).detach()
        relative_code = self._relative_code_from_primitives(
            magnitude=magnitude,
            support_mask=support,
            active_mean=active_mean,
        )
        return magnitude, active_mean, relative_code

    def _relative_coefficient_code(
        self,
        *,
        support_mask: torch.Tensor,
        active_mean_override: torch.Tensor | None = None,
    ) -> torch.Tensor:
        return self._relative_coefficient_components(
            support_mask=support_mask,
            active_mean_override=active_mean_override,
        )[2]

    def dictionary_scale(self) -> torch.Tensor:
        if self.dictionary_role in {"attention_q", "attention_k", "attention_v", "attention_o"}:
            # Attention support-mean corrections are applied once at the functional
            # QK/VO group, never independently on Q/K/V/O projections.
            return self.dictionary_log_scale.exp()
        return (self.dictionary_log_scale + self.relative_coordinate_log_scale).exp()

    def quantized_coefficient_code(
        self,
        coefficient: torch.Tensor | None = None,
        *,
        support_mask: torch.Tensor | None = None,
        active_mean_override: torch.Tensor | None = None,
    ) -> torch.Tensor:
        """Return the actual positive relative-C forward code.

        The sole trainable C parameter is the direct bounded positive magnitude.
        Explicit overrides used by swap/audit paths are already materialized codes
        and are returned unchanged.
        """

        if coefficient is not None and coefficient is not self.coefficient_magnitude:
            return coefficient
        if not bool(getattr(self, "relative_coefficient_enabled", False)):
            return self.coefficient_magnitude if coefficient is None else coefficient
        support = support_mask
        if support is None:
            support = self._current_relative_support_mask(device=self.coefficient_magnitude.device)
        return self._relative_coefficient_code(
            support_mask=support,
            active_mean_override=active_mean_override,
        )

    @torch.no_grad()
    def clamp_quantized_coefficient_latent_(self) -> None:
        """Keep the sole positive C parameter inside the configured bounds."""

        minimum = float(self.relative_coefficient_min_ratio)
        maximum = float(self.relative_coefficient_max_ratio)
        self.coefficient_magnitude.clamp_(min=minimum, max=maximum)

    def _static_coefficient_normalization_support(self, coefficient: torch.Tensor) -> torch.Tensor:
        # Retained name for generic diagnostics; current DiR uses it as the static hard
        # support and performs no RMS/L2 normalization.
        return self._static_relative_support_mask(device=coefficient.device)


    # --- Relative-support coordinate transitions -----------------------------
    def _relative_support_coordinate_correction_value_(
        self,
        old_support: torch.Tensor,
        new_support: torch.Tensor,
        *,
        old_mean_override: torch.Tensor | None = None,
        magnitude_override: torch.Tensor | None = None,
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        """Return the exact active-mean coordinate correction without mutation."""

        old_mask = old_support.to(device=self.coefficient_magnitude.device, dtype=torch.bool)
        new_mask = new_support.to(device=self.coefficient_magnitude.device, dtype=torch.bool)
        if int(old_mask.numel()) != self.atom_count or int(new_mask.numel()) != self.atom_count:
            raise RuntimeError("relative-C support correction mask shape mismatch")
        magnitude = (
            self._bounded_relative_magnitude(detach=True).float()
            if magnitude_override is None
            else magnitude_override.detach().float().to(device=old_mask.device)
        )
        old_mean = (
            self._masked_active_mean(magnitude, old_mask)
            if old_mean_override is None
            else old_mean_override.detach().float().to(device=magnitude.device)
        )
        new_mean = self._masked_active_mean(magnitude, new_mask)
        correction = new_mean.log() - old_mean.log()
        survivor_count = (old_mask & new_mask).sum()
        spread = correction.new_zeros(())
        return correction, survivor_count, old_mean, new_mean, spread

    @torch.no_grad()
    def _relative_support_coordinate_correction_tensor_(
        self,
        old_support: torch.Tensor,
        new_support: torch.Tensor,
        *,
        old_mean_override: torch.Tensor | None = None,
        magnitude_override: torch.Tensor | None = None,
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        """Apply an explicit support-coordinate correction outside the hot path."""

        result = self._relative_support_coordinate_correction_value_(
            old_support,
            new_support,
            old_mean_override=old_mean_override,
            magnitude_override=magnitude_override,
        )
        correction, survivor_count, _old_mean, new_mean, _spread = result
        correction_for_state = correction.to(
            device=self.relative_coordinate_log_scale.device,
            dtype=self.relative_coordinate_log_scale.dtype,
        )
        if self.dictionary_role in {"attention_q", "attention_k", "attention_v", "attention_o"}:
            self.relative_support_direct_log_correction.add_(correction_for_state)
            self._relative_support_direct_correction_seen = True
        else:
            self.relative_coordinate_log_scale.add_(correction_for_state)
        self._last_relative_support_correction_log_factor = correction.detach()
        self._last_relative_support_correction_survivors = survivor_count.detach()
        self._last_relative_coefficient_active_mean = new_mean.detach()
        return result

    @torch.no_grad()
    def consume_relative_support_direct_log_correction_(self) -> torch.Tensor:
        if not bool(self._relative_support_direct_correction_seen):
            return self.relative_support_direct_log_correction.new_zeros(())
        correction = self.relative_support_direct_log_correction.detach().clone()
        self.relative_support_direct_log_correction.zero_()
        self._relative_support_direct_correction_seen = False
        return correction

    @torch.no_grad()
    def queue_relative_support_transition_(
        self,
        old_support: torch.Tensor,
        new_support: torch.Tensor,
    ) -> None:
        """Queue support identities; compute the correction after C updates."""

        old_mask = old_support.to(device=self.coefficient_magnitude.device, dtype=torch.bool)
        new_mask = new_support.to(device=self.coefficient_magnitude.device, dtype=torch.bool)
        if int(old_mask.numel()) != int(self.atom_count) or int(new_mask.numel()) != int(self.atom_count):
            raise RuntimeError("relative-C queued support must match atom_count")
        self.relative_support_pending_old_mask.copy_(old_mask.to(
            device=self.relative_support_pending_old_mask.device, dtype=torch.bool
        ))
        self.relative_support_pending_new_mask.copy_(new_mask.to(
            device=self.relative_support_pending_new_mask.device, dtype=torch.bool
        ))
        self._relative_support_pending_transition_seen = True
        self._last_relative_support_correction_survivors = None

    @torch.no_grad()
    def commit_pending_relative_support_transition_(self, *, apply_local_scale: bool) -> torch.Tensor:
        """Commit a queued transition using post-optimizer, post-clamp C."""

        if not bool(self._relative_support_pending_transition_seen):
            return self.relative_coordinate_log_scale.new_zeros(())
        old_mask = self.relative_support_pending_old_mask.to(
            device=self.coefficient_magnitude.device, dtype=torch.bool
        )
        new_mask = self.relative_support_pending_new_mask.to(
            device=self.coefficient_magnitude.device, dtype=torch.bool
        )
        magnitude = self._bounded_relative_magnitude(detach=True).float()
        old_mean, new_mean = self._paired_masked_active_means(magnitude, old_mask, new_mask)
        correction = new_mean.log() - old_mean.log()
        if apply_local_scale:
            self.relative_coordinate_log_scale.add_(correction.to(
                device=self.relative_coordinate_log_scale.device,
                dtype=self.relative_coordinate_log_scale.dtype,
            ))
        self.forward_routed_previous_support.copy_(new_mask.to(
            device=self.forward_routed_previous_support.device, dtype=torch.bool
        ))
        self._forward_routed_support_seen = True
        self._last_relative_coefficient_active_mean = new_mean.detach()
        self._last_relative_support_correction_log_factor = correction.detach()
        self._last_relative_support_correction_survivors = (old_mask & new_mask).sum().detach()
        committed = correction.detach().clone()
        self.relative_support_pending_old_mask.zero_()
        self.relative_support_pending_new_mask.zero_()
        self._relative_support_pending_transition_seen = False
        return committed


    def _effective_coefficient_from_code(self, coeff_code: torch.Tensor) -> torch.Tensor:
        scale = self.dictionary_scale().to(device=coeff_code.device, dtype=coeff_code.dtype)
        coeff = coeff_code * scale
        if self.coefficient_support_is_committed():
            support = self.coefficient_commit_mask.to(device=coeff.device, dtype=coeff.dtype)
            coeff = coeff * support
        if (
            bool(getattr(self, "forward_routed_gate_enabled", False))
            and bool(getattr(self, "forward_routed_gate_use_copied_hard_support_mask", True))
            and self._forward_routed_fixed_support_is_initialized()
        ):
            fixed_support = self.forward_routed_fixed_support_mask.to(device=coeff.device, dtype=coeff.dtype)
            coeff = coeff * fixed_support
        return coeff

    def effective_coefficient(
        self,
        coefficient: torch.Tensor | None = None,
        *,
        support_mask: torch.Tensor | None = None,
        temporary_log_scale: torch.Tensor | None = None,
        active_mean_override: torch.Tensor | None = None,
    ) -> torch.Tensor:
        coeff_code = self.quantized_coefficient_code(
            coefficient,
            support_mask=support_mask,
            active_mean_override=active_mean_override,
        )
        if temporary_log_scale is not None:
            coeff_code = coeff_code * temporary_log_scale.to(
                device=coeff_code.device, dtype=coeff_code.dtype
            ).exp()
        return self._effective_coefficient_from_code(coeff_code)

    def _apply_effective_coefficient_contract(
        self,
        coefficient: torch.Tensor,
        *,
        preserve_zero_support: bool,
    ) -> torch.Tensor:
        """Apply an optional coefficient-contract functional C contract.

        The contract is attached only by the coefficient-contract matrix controller. It is
        intentionally functional: Condition B bounds the effective C used by
        both route selection and the forward pass, while Condition C replaces
        endpoint-active effective C exactly. Normal experiments see no change.
        """

        mask = getattr(self, "_coefficient_contract_mask", None)
        mode = str(getattr(self, "_coefficient_contract_mode", "none"))
        if mode == "none" or not isinstance(mask, torch.Tensor):
            return coefficient
        mask = mask.to(device=coefficient.device, dtype=torch.bool).reshape(-1)
        if int(mask.numel()) != int(coefficient.numel()):
            raise RuntimeError("coefficient-contract effective-C contract mask length does not match atom_count")
        apply_mask = mask
        if preserve_zero_support:
            apply_mask = apply_mask & coefficient.detach().ne(0)
        if mode == "bounded":
            lower = getattr(self, "_coefficient_contract_lower", None)
            upper = getattr(self, "_coefficient_contract_upper", None)
            if not isinstance(lower, torch.Tensor) or not isinstance(upper, torch.Tensor):
                raise RuntimeError("coefficient-contract bounded effective-C contract is missing limits")
            lower = lower.to(device=coefficient.device, dtype=coefficient.dtype).reshape(-1)
            upper = upper.to(device=coefficient.device, dtype=coefficient.dtype).reshape(-1)
            bounded = torch.maximum(torch.minimum(coefficient, upper), lower)
            return torch.where(apply_mask, bounded, coefficient)
        if mode == "frozen":
            frozen = getattr(self, "_coefficient_contract_frozen", None)
            if not isinstance(frozen, torch.Tensor):
                raise RuntimeError("coefficient-contract frozen effective-C contract is missing endpoint values")
            frozen = frozen.to(device=coefficient.device, dtype=coefficient.dtype).reshape(-1)
            return torch.where(apply_mask, frozen, coefficient)
        raise RuntimeError(f"Unsupported coefficient-contract effective-C contract mode: {mode!r}")


    def atom_contribution_masses(
        self,
        coefficient: torch.Tensor | None = None,
    ) -> torch.Tensor:
        """Return the lightweight parameter-side contribution proxy for A1f/A1g.

        Training contribution diagnostics use this cheap proxy. It is not an
        activation-aware sample contribution. Recorded eval
        usage rows overwrite the public ``contribution_*`` support fields with
        activation-aware metrics when an eval loader is available, while this
        proxy is still reported under ``parameter_contribution_proxy_*``.
        """

        coeff_code = self.quantized_coefficient_code(self.coefficient_magnitude if coefficient is None else coefficient)
        coeff = coeff_code * self.dictionary_scale().to(device=coeff_code.device, dtype=coeff_code.dtype)
        if self.coefficient_support_is_committed():
            support = self.coefficient_commit_mask.to(device=coeff.device, dtype=coeff.dtype)
            coeff = coeff * support
        if (
            bool(getattr(self, "forward_routed_gate_enabled", False))
            and bool(getattr(self, "forward_routed_gate_use_copied_hard_support_mask", True))
            and self._forward_routed_fixed_support_is_initialized()
        ):
            fixed_support = self.forward_routed_fixed_support_mask.to(device=coeff.device, dtype=coeff.dtype)
            coeff = coeff * fixed_support
        row_atoms, col_atoms = self._row_and_col_atoms()
        row_norm = row_atoms.norm(dim=0).to(device=coeff.device, dtype=coeff.dtype).clamp_min(1e-12)
        col_norm = col_atoms.norm(dim=0).to(device=coeff.device, dtype=coeff.dtype).clamp_min(1e-12)
        return coeff.abs() * row_norm * col_norm

    def current_weight(self) -> torch.Tensor:
        return self.dictionary_weight(self.coefficient_magnitude)


    # --- Routed support and gate execution -----------------------------------
    def _forward_solution_entropy_uses_fixed_support_mask_metrics_only(self) -> bool:
        return str(getattr(self, "forward_solution_entropy_mass_mode", "")).strip().lower() in {
            "fixed_source_hard_support_mask_metrics_only",
            "fixed_hard_support_mask_metrics_only",
            "copied_hard_support_mask_metrics_only",
        }

    def _forward_routed_fixed_support_fast_mask(self, coeff: torch.Tensor) -> torch.Tensor | None:
        """Return a copied hard-route mask when the fixed-support fast path is exact.

        This path is used only when route mass diagnostics are explicitly skipped.
        It lets fixed-support training and fixed-mask evaluation diagnostics
        slice the atom dimension before
        projection instead of computing every atom and multiplying zeros
        afterward.
        """

        if bool(getattr(self, "_fixed_support_cache_disabled", False)):
            return None
        if not bool(getattr(self, "forward_routed_gate_enabled", False)):
            return None
        if bool(getattr(self, "forward_solution_entropy_enabled", False)) and not self._forward_solution_entropy_uses_fixed_support_mask_metrics_only():
            return None
        train_use_ema_support = bool(self.training) and bool(getattr(self, "forward_routed_gate_train_use_ema_support", False))
        eval_use_ema_support = (not bool(self.training)) and bool(getattr(self, "forward_routed_gate_eval_use_ema_support", False))
        if not bool(train_use_ema_support or eval_use_ema_support):
            return None
        if not bool(getattr(self, "forward_routed_gate_use_copied_hard_support_mask", True)):
            return None
        if not self._forward_routed_fixed_support_is_initialized():
            return None
        if not bool(getattr(self, "forward_routed_gate_skip_route_mass_when_using_fixed_support", False)):
            return None
        mask = self.forward_routed_fixed_support_mask.to(device=coeff.device, dtype=torch.bool)
        if int(mask.numel()) != int(coeff.numel()):
            return None
        return mask

    def _record_forward_routed_fixed_support_fast_metrics(
        self,
        hard_mask: torch.Tensor,
        *,
        dtype: torch.dtype,
    ) -> None:
        hard_mask_detached = hard_mask.detach().to(dtype=torch.bool)
        hard_gate_detached = hard_mask_detached.to(dtype=dtype)
        cached = self._fixed_support_route_metrics_cache
        if cached is None:
            pre_route_neff, pre_route_mass95 = _route_distribution_neff_and_mass95_tensors(hard_gate_detached)
            with torch.no_grad():
                update_support_diagnostics = bool(self.training)
                previous_support = (
                    self.forward_routed_previous_support.to(device=hard_mask_detached.device)
                    if self._forward_routed_support_seen
                    else self._static_relative_support_mask(device=hard_mask_detached.device)
                )
                if update_support_diagnostics:
                    # The fixed mask is already part of _static_relative_support_mask.
                    # Any real anchor transition is applied before this fast path,
                    # so repeated fixed forwards must never queue
                    # another zero coordinate correction.
                    union_denominator = (previous_support | hard_mask_detached).sum().clamp_min(1)
                    support_jaccard = (previous_support & hard_mask_detached).sum().float().div(union_denominator.float())
                    self.forward_routed_support_union.logical_or_(hard_mask_detached.to(device=self.forward_routed_support_union.device))
                    self.forward_routed_previous_support.copy_(hard_mask_detached.to(device=self.forward_routed_previous_support.device))
                    self._forward_routed_support_seen = True
                else:
                    previous_jaccard = getattr(self, "_last_forward_routed_gate_support_jaccard", None)
                    support_jaccard = (
                        previous_jaccard.to(device=hard_mask_detached.device)
                        if isinstance(previous_jaccard, torch.Tensor)
                        else torch.ones((), device=hard_mask_detached.device)
                    )
            cached = {
                "active_atoms": hard_gate_detached.sum().detach(),
                "active_ratio": hard_gate_detached.mean().detach() if int(hard_gate_detached.numel()) > 0 else hard_gate_detached.new_zeros(()),
                "support_jaccard": support_jaccard.detach(),
                "neff": pre_route_neff.detach(),
                "mass95": pre_route_mass95.detach(),
            }
            self._fixed_support_route_metrics_cache = cached
        self._last_forward_routed_gate_enabled = True
        self._last_forward_routed_gate_alpha = float(getattr(self, "forward_routed_gate_alpha", 1.0))
        self._last_forward_routed_gate_active_atoms = cached["active_atoms"].to(device=hard_gate_detached.device, dtype=hard_gate_detached.dtype)
        self._last_forward_routed_gate_active_ratio = cached["active_ratio"].to(device=hard_gate_detached.device, dtype=hard_gate_detached.dtype)
        self._last_forward_routed_gate_straight_through = False
        self._last_forward_routed_gate_ema_support = True
        self._last_forward_routed_gate_fixed_hard_support = True
        self._last_forward_routed_route_mass_skipped = True
        self._last_forward_routed_hard_gate = hard_gate_detached
        self._last_forward_routed_soft_gate = hard_gate_detached
        self._last_forward_routed_gate_support_jaccard = cached["support_jaccard"].to(device=hard_gate_detached.device)
        self._last_forward_routed_pre_route_neff = cached["neff"].to(device=hard_gate_detached.device)
        self._last_forward_routed_pre_route_mass95_atoms = cached["mass95"].to(device=hard_gate_detached.device)
        self._last_forward_routed_post_route_neff = self._last_forward_routed_pre_route_neff
        self._last_forward_routed_post_route_mass95_atoms = self._last_forward_routed_pre_route_mass95_atoms

    def _record_forward_solution_fixed_support_metrics_from_mask(self, hard_mask: torch.Tensor) -> None:
        cache = self._fixed_support_solution_metrics_cache
        mass = hard_mask.detach().to(device=self.coefficient_magnitude.device, dtype=self.coefficient_magnitude.dtype).float()
        if cache is None:
            entropy_eps = float(getattr(self, "forward_solution_entropy_eps", 1e-8))
            denominator = mass.sum().clamp_min(entropy_eps)
            q = mass / denominator
            entropy = -(q * q.clamp_min(entropy_eps).log()).sum() / math.log(max(2, int(self.atom_count)))
            neff, mass95 = _route_distribution_neff_and_mass95_tensors(mass)
            active_count_tensor = mass.sum()
            # One synchronized conversion per immutable support mask. Subsequent
            # fixed-support forwards reuse these Python values.
            cache = {
                "entropy": float(entropy.detach().cpu()),
                "neff": float(neff.detach().cpu()),
                "mass95": float(mass95.detach().cpu()),
                "active_count": float(active_count_tensor.detach().cpu()),
            }
            self._fixed_support_solution_metrics_cache = cache
        entropy_value = cache["entropy"]
        neff_value = cache["neff"]
        mass95_value = cache["mass95"]
        active_count = cache["active_count"]
        entropy_eps = float(getattr(self, "forward_solution_entropy_eps", 1e-8))
        q = mass / mass.sum().clamp_min(entropy_eps)
        atom_entropy = _dictionary_entropy_ratio_per_atom(self).to(device=mass.device, dtype=mass.dtype)
        used_atom_entropy_value = float((q * atom_entropy).sum().detach().cpu())
        self._last_forward_solution_entropy_mean = entropy_value
        self._last_forward_solution_entropy_p95 = entropy_value
        self._last_forward_solution_neff_mean = neff_value
        self._last_forward_solution_neff_p95 = neff_value
        self._last_forward_solution_mass95_atoms_mean = mass95_value
        self._last_forward_solution_mass95_atoms_p95 = mass95_value
        self._last_forward_solution_loss_mass_entropy_mean = entropy_value
        self._last_forward_solution_loss_mass_entropy_p95 = entropy_value
        self._last_forward_solution_loss_mass_neff_mean = neff_value
        self._last_forward_solution_loss_mass_neff_p95 = neff_value
        self._last_forward_solution_loss_mass_mass95_atoms_mean = mass95_value
        self._last_forward_solution_loss_mass_mass95_atoms_p95 = mass95_value
        self._last_forward_solution_used_atom_entropy = used_atom_entropy_value
        self._last_global_solution_entropy = entropy_value
        self._last_global_solution_neff_atoms = neff_value
        self._last_global_solution_support_active_atoms = active_count
        self._last_global_solution_support_inactive_atoms = float(max(0.0, float(self.atom_count) - active_count))
        self._last_global_solution_entmax_alpha = float(getattr(self, "forward_routed_gate_alpha", getattr(self, "forward_solution_entmax_alpha", 1.0)))
        self._last_global_solution_hard_support_enabled = True

    def _prepare_forward_route_state(
        self,
        *,
        projected: torch.Tensor,
        coeff: torch.Tensor,
    ) -> _ForwardRouteState:
        mass_eps = float(getattr(self, "forward_routed_gate_score_eps", 1e-6))
        alpha = float(getattr(self, "forward_routed_gate_alpha", 1.0))
        tolerance = float(
            getattr(self, "forward_routed_gate_support_tolerance", 1e-8)
        )
        atom_count = int(coeff.numel())
        if atom_count <= 0:
            raise RuntimeError(
                "forward_routed_gate requires at least one coefficient atom"
            )
        if int(projected.shape[-1]) != atom_count:
            raise RuntimeError(
                "forward_routed_gate projected atom dimension "
                f"{int(projected.shape[-1])} does not match coefficient atom count "
                f"{atom_count}"
            )

        train_use_ema_support = bool(self.training) and bool(
            getattr(self, "forward_routed_gate_train_use_ema_support", False)
        )
        eval_use_ema_support = (not bool(self.training)) and bool(
            getattr(self, "forward_routed_gate_eval_use_ema_support", False)
        )
        requested_ema_support = bool(
            train_use_ema_support or eval_use_ema_support
        )
        ema_initialized = self._global_solution_usage_ema_is_initialized()
        fixed_support_initialized = self._forward_routed_fixed_support_is_initialized()
        use_copied_hard_support_mask = bool(
            requested_ema_support
            and fixed_support_initialized
            and getattr(
                self,
                "forward_routed_gate_use_copied_hard_support_mask",
                True,
            )
        )
        use_ema_support = bool(
            requested_ema_support
            and (use_copied_hard_support_mask or ema_initialized)
        )
        if (
            requested_ema_support
            and not use_ema_support
            and bool(getattr(self, "forward_routed_gate_require_ema_support", False))
        ):
            raise RuntimeError(
                "forward_routed_gate requested fixed support, but no copied hard mask "
                "or initialized EMA route support is available"
            )
        skip_route_mass = bool(
            use_ema_support
            and getattr(
                self,
                "forward_routed_gate_skip_route_mass_when_using_fixed_support",
                False,
            )
        )

        route_mass: torch.Tensor | None = None
        route_candidate_mask: torch.Tensor | None = None
        residual_route_mode = bool(
            getattr(self, "_residual_route_enabled_cached", False)
        )
        if not skip_route_mass:
            projected_mean_abs = projected.abs().reshape(-1, atom_count).mean(dim=0)
            route_mass = projected_mean_abs * coeff.abs().to(
                device=projected.device,
                dtype=projected.dtype,
            )
            if (
                bool(
                    getattr(
                        self,
                        "forward_routed_gate_route_mass_parity_check",
                        True,
                    )
                )
                and not bool(
                    getattr(
                        self,
                        "_forward_routed_gate_route_mass_parity_checked",
                        False,
                    )
                )
            ):
                with torch.no_grad():
                    coeff_view_shape = (
                        *([1] * max(0, int(projected.ndim) - 1)),
                        atom_count,
                    )
                    reference_mass = (
                        projected.detach()
                        * coeff.detach()
                        .to(device=projected.device, dtype=projected.dtype)
                        .reshape(coeff_view_shape)
                    ).abs().reshape(-1, atom_count).mean(dim=0)
                    absolute_error = (
                        route_mass.detach().float() - reference_mass.float()
                    ).abs()
                    max_abs_error = absolute_error.amax()
                    max_relative_error = (
                        absolute_error
                        / reference_mass.float().abs().clamp_min(1e-12)
                    ).amax()
                    tolerance_value = float(
                        getattr(
                            self,
                            "forward_routed_gate_route_mass_parity_tolerance",
                            1e-6,
                        )
                    )
                    allowed_error = tolerance_value * (
                        1.0 + reference_mass.float().abs()
                    )
                    torch._assert_async(
                        (absolute_error <= allowed_error).all(),
                        "factorized route mass does not match broadcast reference",
                    )
                    self._last_forward_routed_route_mass_parity_max_abs_error = (
                        max_abs_error.detach()
                    )
                    self._last_forward_routed_route_mass_parity_max_relative_error = (
                        max_relative_error.detach()
                    )
                    self._forward_routed_gate_route_mass_parity_checked = True

            route_trainable_mask = getattr(self, "_route_trainable_mask", None)
            if residual_route_mode:
                if not isinstance(route_trainable_mask, torch.Tensor):
                    raise RuntimeError(
                        "coefficient-contract residual route mask is missing"
                    )
                route_candidate_mask = route_trainable_mask.to(
                    device=route_mass.device,
                    dtype=torch.bool,
                ).reshape(-1)
                if int(route_candidate_mask.numel()) != atom_count:
                    raise RuntimeError(
                        "coefficient-contract route-trainable mask length does not "
                        "match atom_count"
                    )
                force_on = getattr(self, "_route_force_on_mask", None)
                if not isinstance(force_on, torch.Tensor):
                    raise RuntimeError(
                        "coefficient-contract residual route requires the protected "
                        "active mask"
                    )
                force_on = force_on.to(
                    device=route_mass.device,
                    dtype=torch.bool,
                ).reshape(-1)
                protected_mass = route_mass.masked_select(force_on)
                protected_mean = (
                    protected_mass.mean()
                    if int(protected_mass.numel()) > 0
                    else route_mass.mean()
                )
                route_mass = (
                    route_mass / protected_mean.detach().clamp_min(mass_eps)
                ) * route_candidate_mask.to(dtype=route_mass.dtype)

            if bool(self.training) and not train_use_ema_support:
                with torch.no_grad():
                    route_state = route_mass.detach().float()
                    if not residual_route_mode:
                        route_state = route_state / route_state.sum().clamp_min(1e-12)
                    ema_initialized = self._update_forward_routed_usage_ema_(
                        route_state,
                        residual_route_mode=residual_route_mode,
                        ema_initialized=ema_initialized,
                    )
                    if (
                        requested_ema_support
                        and not use_ema_support
                        and self._global_solution_usage_ema_is_initialized()
                    ):
                        use_ema_support = True

        ema_support_snapshot: torch.Tensor | None = None
        if use_ema_support and not use_copied_hard_support_mask:
            ema_support_snapshot = self.global_solution_usage_ema.detach().to(
                device=projected.device,
                dtype=projected.dtype,
            ).clone()
        if (
            route_mass is None
            and not use_copied_hard_support_mask
            and ema_support_snapshot is None
        ):
            raise RuntimeError(
                "forward_routed_gate requires route_mass unless fixed or EMA support "
                "is available"
            )

        return _ForwardRouteState(
            mass_eps=mass_eps,
            alpha=alpha,
            tolerance=tolerance,
            atom_count=atom_count,
            train_use_ema_support=train_use_ema_support,
            requested_ema_support=requested_ema_support,
            use_copied_hard_support_mask=use_copied_hard_support_mask,
            use_ema_support=use_ema_support,
            skip_route_mass=skip_route_mass,
            route_mass=route_mass,
            route_candidate_mask=route_candidate_mask,
            residual_route_mode=residual_route_mode,
            ema_support_snapshot=ema_support_snapshot,
        )

    def _select_forward_route_gate(
        self,
        *,
        projected: torch.Tensor,
        state: _ForwardRouteState,
    ) -> _ForwardRouteSelection:
        route_candidate_mask = state.route_candidate_mask
        candidate_indices: torch.Tensor | None = None
        if route_candidate_mask is None:
            configured_candidate_mask = getattr(self, "_route_trainable_mask", None)
            if bool(getattr(self, "_residual_route_enabled_cached", False)):
                if not isinstance(configured_candidate_mask, torch.Tensor):
                    raise RuntimeError(
                        "coefficient-contract residual route mask is missing"
                    )
                route_candidate_mask = configured_candidate_mask.to(
                    device=projected.device,
                    dtype=torch.bool,
                ).reshape(-1)
                if int(route_candidate_mask.numel()) != state.atom_count:
                    raise RuntimeError(
                        "coefficient-contract route-trainable mask length does not "
                        "match atom_count"
                    )
        if route_candidate_mask is not None:
            candidate_indices = torch.nonzero(
                route_candidate_mask,
                as_tuple=False,
            ).reshape(-1)

        def candidate_values(value: torch.Tensor) -> torch.Tensor:
            if candidate_indices is None:
                return value
            return value.index_select(0, candidate_indices)

        def expand_candidate_values(
            value: torch.Tensor,
            *,
            dtype: torch.dtype,
        ) -> torch.Tensor:
            if candidate_indices is None:
                return value.to(dtype=dtype)
            expanded = torch.zeros(
                state.atom_count,
                device=value.device,
                dtype=dtype,
            )
            expanded.index_copy_(0, candidate_indices, value.to(dtype=dtype))
            return expanded

        entmax_iterations = max(
            1,
            int(getattr(self, "forward_routed_gate_entmax_iterations", 16) or 16),
        )
        compile_entmax = bool(
            getattr(self, "forward_routed_gate_compile_entmax_bisection", True)
        )
        compiled_eager_tolerance = float(
            getattr(
                self,
                "forward_routed_gate_entmax_compile_parity_tolerance",
                1e-6,
            )
        )
        straight_through_enabled = bool(self.training) and bool(
            getattr(self, "forward_routed_gate_straight_through", True)
        )
        compile_requested = False

        if state.use_copied_hard_support_mask:
            hard_mask = self.forward_routed_fixed_support_mask.to(
                device=projected.device,
                dtype=torch.bool,
            )
            hard_gate = hard_mask.to(dtype=projected.dtype)
            soft_gate = hard_gate
        elif state.ema_support_snapshot is not None:
            ema_candidate = candidate_values(state.ema_support_snapshot)
            route_candidate = (
                candidate_values(state.route_mass)
                if state.route_mass is not None
                else None
            )
            if candidate_indices is not None and route_candidate is not None:
                seed_from_route = ema_candidate.detach().sum().le(state.mass_eps)
                ema_candidate = torch.where(
                    seed_from_route,
                    route_candidate.detach(),
                    ema_candidate,
                )
            if state.residual_route_mode:
                null_logit = ema_candidate.new_zeros((1,))
                ema_logits = torch.cat(
                    (ema_candidate.clamp_min(state.mass_eps).log(), null_logit),
                    dim=0,
                ).detach()
            else:
                ema_distribution = ema_candidate / ema_candidate.sum().clamp_min(
                    state.mass_eps
                )
                ema_logits = ema_distribution.clamp_min(state.mass_eps).log().detach()

            if straight_through_enabled and route_candidate is not None:
                if state.residual_route_mode:
                    route_logits = torch.cat(
                        (
                            route_candidate.clamp_min(state.mass_eps).log(),
                            route_candidate.new_zeros((1,)),
                        ),
                        dim=0,
                    )
                else:
                    route_distribution = route_candidate / route_candidate.sum().clamp_min(
                        state.mass_eps
                    )
                    route_logits = route_distribution.clamp_min(state.mass_eps).log()
                paired_probability = _entmax_alpha_last_dim(
                    torch.stack((ema_logits, route_logits), dim=0),
                    state.alpha,
                    iterations=entmax_iterations,
                    compile_generic_cuda=compile_entmax,
                    support_tolerance=state.tolerance,
                    compiled_eager_tolerance=compiled_eager_tolerance,
                ).to(device=projected.device, dtype=projected.dtype)
                if state.residual_route_mode:
                    hard_probability_candidate = paired_probability[0, :-1].detach()
                    soft_probability_candidate = paired_probability[1, :-1]
                    soft_gate_candidate = soft_probability_candidate / paired_probability[
                        1
                    ].max().clamp_min(1e-12)
                else:
                    hard_probability_candidate = paired_probability[0].detach()
                    soft_probability_candidate = paired_probability[1]
                    soft_gate_candidate = soft_probability_candidate / (
                        soft_probability_candidate.max().clamp_min(1e-12)
                    )
                compile_requested = bool(
                    1.0 + 1e-8 < state.alpha < 2.0 - 1e-8
                    and compile_entmax
                    and projected.is_cuda
                )
            else:
                with torch.no_grad():
                    hard_probability_full = _entmax_alpha_1d(
                        ema_logits,
                        state.alpha,
                        iterations=entmax_iterations,
                        compile_generic_cuda=compile_entmax,
                        support_tolerance=state.tolerance,
                        compiled_eager_tolerance=compiled_eager_tolerance,
                    ).to(device=projected.device, dtype=projected.dtype)
                hard_probability_candidate = (
                    hard_probability_full[:-1]
                    if state.residual_route_mode
                    else hard_probability_full
                )
                soft_gate_candidate = None

            hard_mask_candidate = hard_probability_candidate > state.tolerance
            if not state.residual_route_mode:
                hard_mask_candidate = hard_mask_candidate | F.one_hot(
                    torch.argmax(hard_probability_candidate).reshape(()),
                    num_classes=int(hard_probability_candidate.numel()),
                ).to(device=hard_probability_candidate.device, dtype=torch.bool)
            hard_mask = expand_candidate_values(
                hard_mask_candidate,
                dtype=torch.bool,
            )
            hard_gate = hard_mask.to(dtype=projected.dtype)
            soft_gate = (
                hard_gate
                if soft_gate_candidate is None
                else expand_candidate_values(
                    soft_gate_candidate,
                    dtype=projected.dtype,
                )
            )
        else:
            assert state.route_mass is not None
            route_candidate = candidate_values(state.route_mass)
            if state.residual_route_mode:
                route_logits = torch.cat(
                    (
                        route_candidate.clamp_min(state.mass_eps).log(),
                        route_candidate.new_zeros((1,)),
                    ),
                    dim=0,
                )
            else:
                route_distribution = route_candidate / route_candidate.sum().clamp_min(
                    state.mass_eps
                )
                route_logits = route_distribution.clamp_min(state.mass_eps).log()
            current_probability_full = _entmax_alpha_1d(
                route_logits,
                state.alpha,
                iterations=entmax_iterations,
                compile_generic_cuda=compile_entmax,
                support_tolerance=state.tolerance,
                compiled_eager_tolerance=compiled_eager_tolerance,
            ).to(device=projected.device, dtype=projected.dtype)
            if state.residual_route_mode:
                current_probability_candidate = current_probability_full[:-1]
                soft_gate_candidate = current_probability_candidate / (
                    current_probability_full.max().clamp_min(1e-12)
                )
            else:
                current_probability_candidate = current_probability_full
                soft_gate_candidate = current_probability_candidate / (
                    current_probability_candidate.max().clamp_min(1e-12)
                )
            hard_mask_candidate = current_probability_candidate > state.tolerance
            if not state.residual_route_mode:
                hard_mask_candidate = hard_mask_candidate | F.one_hot(
                    torch.argmax(current_probability_candidate.detach()).reshape(()),
                    num_classes=int(current_probability_candidate.numel()),
                ).to(device=current_probability_candidate.device, dtype=torch.bool)
            hard_mask = expand_candidate_values(
                hard_mask_candidate,
                dtype=torch.bool,
            )
            soft_gate = expand_candidate_values(
                soft_gate_candidate,
                dtype=projected.dtype,
            )
            hard_gate = hard_mask.to(dtype=projected.dtype)
            compile_requested = bool(
                1.0 + 1e-8 < state.alpha < 2.0 - 1e-8
                and compile_entmax
                and projected.is_cuda
            )

        route_force_on_mask = getattr(self, "_route_force_on_mask", None)
        if isinstance(route_force_on_mask, torch.Tensor):
            route_force_on_mask = route_force_on_mask.to(
                device=hard_mask.device,
                dtype=torch.bool,
            ).reshape(-1)
            if int(route_force_on_mask.numel()) != state.atom_count:
                raise RuntimeError(
                    "coefficient-contract route force-on mask length does not match "
                    "atom_count"
                )
            hard_mask = hard_mask | route_force_on_mask
            hard_gate = hard_mask.to(dtype=projected.dtype)
            soft_gate = torch.where(
                route_force_on_mask,
                torch.ones_like(soft_gate),
                soft_gate,
            )

        return _ForwardRouteSelection(
            hard_mask=hard_mask,
            hard_gate=hard_gate,
            soft_gate=soft_gate,
            compile_requested=compile_requested,
            entmax_iterations=entmax_iterations,
        )

    def _record_forward_route_result(
        self,
        *,
        projected: torch.Tensor,
        state: _ForwardRouteState,
        selection: _ForwardRouteSelection,
    ) -> torch.Tensor:
        entmax_runtime = _entmax_runtime_snapshot(selection.entmax_iterations)
        self._last_entmax_compile_requested = selection.compile_requested
        self._last_entmax_compile_attempted = bool(
            selection.compile_requested
            and entmax_runtime.get("compile_attempted", False)
        )
        self._last_entmax_compile_succeeded = bool(
            selection.compile_requested
            and entmax_runtime.get("compile_succeeded", False)
        )
        self._last_entmax_compiled_active = bool(
            selection.compile_requested
            and entmax_runtime.get("compiled_active", False)
        )
        self._last_entmax_compile_validation_count = int(
            entmax_runtime.get("validation_count", 0)
        )
        self._last_entmax_compile_fallback_count = int(
            entmax_runtime.get("fallback_count", 0)
        )
        self._last_entmax_compiled_eager_max_abs_error = float(
            entmax_runtime.get("compiled_eager_max_abs_error", 0.0)
        )
        self._last_entmax_compiled_eager_support_mismatch_count = int(
            entmax_runtime.get("compiled_eager_support_mismatch_count", 0)
        )
        self._last_entmax_compile_fallback_reason = str(
            entmax_runtime.get("fallback_reason", "")
        )

        if (
            bool(self.training)
            and state.train_use_ema_support
            and state.route_mass is not None
        ):
            with torch.no_grad():
                route_state = state.route_mass.detach().float()
                if not state.residual_route_mode:
                    route_state = route_state / route_state.sum().clamp_min(1e-12)
                self._update_forward_routed_usage_ema_(
                    route_state,
                    residual_route_mode=state.residual_route_mode,
                    ema_initialized=self._global_solution_usage_ema_is_initialized(),
                )

        hard_gate_detached = selection.hard_gate.detach()
        hard_mask_detached = selection.hard_mask.detach()
        record_distribution_diagnostics = bool(
            not self.training
            or bool(getattr(self, "forward_solution_entropy_record_metrics", False))
            or bool(
                getattr(self, "_activation_contribution_measurement_enabled", False)
            )
        )
        if record_distribution_diagnostics:
            if state.route_mass is None:
                support_diagnostic_mass = hard_gate_detached.to(dtype=projected.dtype)
                pre_route_neff, pre_route_mass95 = (
                    _route_distribution_neff_and_mass95_tensors(
                        support_diagnostic_mass
                    )
                )
                post_route_neff, post_route_mass95 = pre_route_neff, pre_route_mass95
            else:
                pre_route_neff, pre_route_mass95 = (
                    _route_distribution_neff_and_mass95_tensors(state.route_mass)
                )
                post_route_neff, post_route_mass95 = (
                    _route_distribution_neff_and_mass95_tensors(
                        state.route_mass
                        * hard_gate_detached.to(dtype=state.route_mass.dtype)
                    )
                )
        else:
            pre_route_neff = None
            pre_route_mass95 = None
            post_route_neff = None
            post_route_mass95 = None

        with torch.no_grad():
            compute_support_diagnostics = bool(record_distribution_diagnostics)
            update_support_state = bool(self.training) and bool(
                record_distribution_diagnostics
            )
            if bool(self.training):
                self.forward_routed_support_union.logical_or_(
                    hard_mask_detached.to(
                        device=self.forward_routed_support_union.device
                    )
                )
            if compute_support_diagnostics:
                previous_support = (
                    self.forward_routed_previous_support.to(
                        device=hard_mask_detached.device
                    )
                    if self._forward_routed_support_seen
                    else self._static_relative_support_mask(
                        device=hard_mask_detached.device
                    )
                )
                union_denominator = (
                    previous_support | hard_mask_detached
                ).sum().clamp_min(1)
                support_jaccard = (
                    (previous_support & hard_mask_detached)
                    .sum()
                    .float()
                    .div(union_denominator.float())
                )
                if update_support_state and not bool(self.training):
                    self.forward_routed_support_union.logical_or_(
                        hard_mask_detached.to(
                            device=self.forward_routed_support_union.device
                        )
                    )
            else:
                previous_jaccard = getattr(
                    self,
                    "_last_forward_routed_gate_support_jaccard",
                    None,
                )
                support_jaccard = (
                    previous_jaccard.to(device=hard_mask_detached.device)
                    if isinstance(previous_jaccard, torch.Tensor)
                    else torch.ones((), device=hard_mask_detached.device)
                )

        straight_through = bool(self.training) and bool(
            getattr(self, "forward_routed_gate_straight_through", True)
        )
        if straight_through:
            gate = (
                selection.hard_gate.detach()
                - selection.soft_gate.detach()
                + selection.soft_gate
            )
        else:
            gate = selection.hard_gate.detach()

        self._last_forward_routed_gate_enabled = True
        self._last_forward_routed_gate_alpha = float(state.alpha)
        self._last_forward_routed_gate_active_atoms = hard_gate_detached.sum()
        self._last_forward_routed_gate_active_ratio = (
            hard_gate_detached.mean()
            if int(hard_gate_detached.numel()) > 0
            else hard_gate_detached.new_zeros(())
        )
        self._last_forward_routed_gate_straight_through = straight_through
        self._last_forward_routed_gate_ema_support = bool(state.use_ema_support)
        self._last_forward_routed_gate_fixed_hard_support = bool(
            state.use_copied_hard_support_mask
        )
        self._last_forward_routed_route_mass_skipped = bool(state.skip_route_mass)
        self._last_forward_routed_hard_gate = hard_gate_detached
        self._last_forward_routed_soft_gate = selection.soft_gate.detach()
        self._last_forward_routed_gate_support_jaccard = support_jaccard.detach()
        self._last_forward_routed_pre_route_neff = pre_route_neff
        self._last_forward_routed_pre_route_mass95_atoms = pre_route_mass95
        self._last_forward_routed_post_route_neff = post_route_neff
        self._last_forward_routed_post_route_mass95_atoms = post_route_mass95
        return gate

    def _forward_routed_gate(
        self,
        *,
        projected: torch.Tensor,
        coeff: torch.Tensor,
    ) -> torch.Tensor:
        """Select the hard routed support and retain the straight-through gradient."""

        state = self._prepare_forward_route_state(
            projected=projected,
            coeff=coeff,
        )
        selection = self._select_forward_route_gate(
            projected=projected,
            state=state,
        )
        return self._record_forward_route_result(
            projected=projected,
            state=state,
            selection=selection,
        )

    @torch.no_grad()

    # --- Measurement-only instrumentation -----------------------------------
    def begin_activation_contribution_measurement_(
        self,
        *,
        threshold: float,
        collect_sample_hard_counts: bool = True,
    ) -> None:
        """Begin bounded post-route contribution accumulation on the layer device."""

        self._activation_contribution_measurement_state = {
            "threshold": float(threshold),
            "mass_sum": torch.zeros(self.atom_count, device=self.coefficient_magnitude.device, dtype=torch.float32),
            "support_sample_count": torch.zeros(self.atom_count, device=self.coefficient_magnitude.device, dtype=torch.float32),
            "pure_c_sum": torch.zeros(self.atom_count, device=self.coefficient_magnitude.device, dtype=torch.float32),
            "abs_pure_c_sum": torch.zeros(self.atom_count, device=self.coefficient_magnitude.device, dtype=torch.float32),
            "c_sum": torch.zeros(self.atom_count, device=self.coefficient_magnitude.device, dtype=torch.float32),
            "abs_c_sum": torch.zeros(self.atom_count, device=self.coefficient_magnitude.device, dtype=torch.float32),
            "route_sum": torch.zeros(self.atom_count, device=self.coefficient_magnitude.device, dtype=torch.float32),
            "d_projection_row_sum": torch.zeros(self.atom_count, device=self.coefficient_magnitude.device, dtype=torch.float32),
            "support_observed_union": torch.zeros(self.atom_count, device=self.coefficient_magnitude.device, dtype=torch.bool),
            "support_observed_intersection": torch.ones(self.atom_count, device=self.coefficient_magnitude.device, dtype=torch.bool),
            "forward_call_count": 0,
            "cached_row_norm": None,
            "cached_active_indices": None,
            "sample_count": 0,
            "collect_sample_hard_counts": bool(collect_sample_hard_counts),
            "sample_hard_counts": [],
        }

    @torch.no_grad()
    def end_activation_contribution_measurement_(self) -> dict[str, Any] | None:
        state = self._activation_contribution_measurement_state
        self._activation_contribution_measurement_state = None
        return state

    @torch.no_grad()
    def _record_activation_contribution_measurement_(
        self,
        *,
        weighted: torch.Tensor,
        row_atoms: torch.Tensor,
        active_indices: torch.Tensor,
        support_mask: torch.Tensor,
        pure_coefficient_code: torch.Tensor,
        route_gate: torch.Tensor | None,
        projected: torch.Tensor,
    ) -> None:
        state = self._activation_contribution_measurement_state
        if not isinstance(state, dict):
            return
        if int(weighted.numel()) <= 0 or int(weighted.shape[-1]) <= 0:
            return
        local_count = int(weighted.shape[-1])
        if int(active_indices.numel()) != local_count or int(support_mask.numel()) != local_count:
            raise RuntimeError("activation contribution measurement support/index shape mismatch")
        local_support = support_mask.to(device=weighted.device, dtype=torch.bool)
        local_indices = active_indices.to(device=weighted.device, dtype=torch.long)
        full_support = torch.zeros(self.atom_count, device=weighted.device, dtype=torch.bool)
        full_support[local_indices] = local_support
        state["support_observed_union"].logical_or_(full_support)
        if int(state.get("forward_call_count", 0)) == 0:
            state["support_observed_intersection"].copy_(full_support)
        else:
            state["support_observed_intersection"].logical_and_(full_support)
        state["forward_call_count"] = int(state.get("forward_call_count", 0)) + 1
        cached_row_norm = state.get("cached_row_norm")
        cached_active_indices = state.get("cached_active_indices")
        cache_matches = bool(
            isinstance(cached_row_norm, torch.Tensor)
            and int(cached_row_norm.numel()) == local_count
            and isinstance(cached_active_indices, torch.Tensor)
            and torch.equal(cached_active_indices.to(device=local_indices.device), local_indices)
        )
        if not cache_matches:
            cached_row_norm = row_atoms.detach().float().norm(dim=0).clamp_min(1e-12)
            state["cached_row_norm"] = cached_row_norm
            state["cached_active_indices"] = local_indices.detach().clone()
        row_norm = cached_row_norm.to(device=weighted.device, dtype=torch.float32)
        flat_mass = weighted.detach().float().abs().reshape(-1, local_count).mul(row_norm.reshape(1, -1))
        sample_count = int(flat_mass.shape[0])
        if sample_count <= 0:
            return
        local_mass_sum = flat_mass.sum(dim=0)
        state["mass_sum"].index_add_(0, local_indices, local_mass_sum)
        support_weight = local_support.to(dtype=torch.float32).mul(float(sample_count))
        state["support_sample_count"].index_add_(0, local_indices, support_weight)
        code = pure_coefficient_code.detach().float().reshape(-1)
        if int(code.numel()) != local_count:
            raise RuntimeError("activation contribution measurement coefficient shape mismatch")
        state["pure_c_sum"].index_add_(0, local_indices, code * support_weight)
        state["abs_pure_c_sum"].index_add_(0, local_indices, code.abs() * support_weight)
        state["c_sum"].index_add_(0, local_indices, code * support_weight)
        state["abs_c_sum"].index_add_(0, local_indices, code.abs() * support_weight)
        if route_gate is None:
            local_route = local_support.to(dtype=torch.float32)
        else:
            local_route = route_gate.detach().float().reshape(-1) * local_support.to(dtype=torch.float32)
        state["route_sum"].index_add_(0, local_indices, local_route * float(sample_count))
        projected_abs = projected.detach().float().abs().reshape(-1, local_count)
        state["d_projection_row_sum"].index_add_(
            0, local_indices, projected_abs.sum(dim=0) * row_norm
        )
        if bool(state.get("collect_sample_hard_counts", True)):
            probability = flat_mass / flat_mass.sum(dim=1, keepdim=True).clamp_min(1e-12)
            state["sample_hard_counts"].append(
                (probability >= float(state["threshold"])).sum(dim=1).detach().cpu()
            )
        state["sample_count"] = int(state["sample_count"]) + sample_count

    # --- Forward computation -------------------------------------------------
    def dictionary_linear(
        self,
        input_tensor: torch.Tensor,
        coefficient: torch.Tensor | None = None,
    ) -> torch.Tensor:
        """Apply the separable Dictionary update without materializing a dense weight."""

        relative_default = bool(getattr(self, "relative_coefficient_enabled", False)) and (
            coefficient is None or coefficient is self.coefficient_magnitude
        )
        initial_support: torch.Tensor | None = None
        bounded_magnitude: torch.Tensor | None = None
        forward_code_full: torch.Tensor | None = None
        queued_support: torch.Tensor | None = None
        if relative_default:
            initial_support = self._current_relative_support_mask(device=self.coefficient_magnitude.device)
            bounded_magnitude = self._prepare_relative_coefficient_magnitude()
            # Route uses raw bounded C. Its normalized mass distribution makes
            # activeMean(C) unnecessary until the hard support is known.
            route_coeff_full = bounded_magnitude
        else:
            route_coeff_full = self.quantized_coefficient_code(
                coefficient, support_mask=initial_support
            )

        if str(getattr(self, "_coefficient_contract_mode", "none")) != "none":
            if relative_default:
                if bounded_magnitude is None or initial_support is None:
                    raise RuntimeError("coefficient-contract effective-C route contract is missing relative-C primitives")
                route_active_mean = self._masked_active_mean(bounded_magnitude, initial_support)
                route_code = self._relative_code_from_primitives(
                    magnitude=bounded_magnitude,
                    support_mask=initial_support,
                    active_mean=route_active_mean,
                )
                route_coeff_full = route_code * self.dictionary_scale().to(
                    device=route_code.device, dtype=route_code.dtype
                )
            else:
                route_coeff_full = route_coeff_full * self.dictionary_scale().to(
                    device=route_coeff_full.device, dtype=route_coeff_full.dtype
                )
            route_coeff_full = self._apply_effective_coefficient_contract(
                route_coeff_full, preserve_zero_support=False
            )

        row_atoms, col_atoms = self._row_and_col_atoms()
        full_row_atoms = row_atoms
        full_col_atoms = col_atoms
        fixed_support_cache_used = False
        active_indices = torch.arange(self.atom_count, device=route_coeff_full.device, dtype=torch.long)
        fixed_route_fast_mask = self._forward_routed_fixed_support_fast_mask(route_coeff_full)
        active = None
        if self.coefficient_support_is_committed() and not bool(getattr(self, "forward_solution_entropy_enabled", False)):
            active = self.coefficient_commit_mask.to(device=route_coeff_full.device, dtype=torch.bool)
        if fixed_route_fast_mask is not None:
            active = fixed_route_fast_mask if active is None else (active & fixed_route_fast_mask)
        route_coeff = route_coeff_full
        if active is not None:
            active_indices, route_coeff, row_atoms, col_atoms = self._fixed_support_active_atoms(
                active=active,
                row_atoms=row_atoms,
                col_atoms=col_atoms,
                coefficient=route_coeff_full,
            )
            fixed_support_cache_used = True

        projected = torch.matmul(input_tensor, col_atoms)
        route_gate: torch.Tensor | None = None
        measurement_support = torch.ones(int(route_coeff.numel()), device=route_coeff.device, dtype=torch.bool)
        if bool(getattr(self, "forward_routed_gate_enabled", False)):
            if fixed_route_fast_mask is not None:
                self._record_forward_routed_fixed_support_fast_metrics(fixed_route_fast_mask, dtype=projected.dtype)
            else:
                route_gate = self._forward_routed_gate(
                    projected=projected,
                    coeff=route_coeff,
                )
                hard_route_support = getattr(self, "_last_forward_routed_hard_gate", None)
                if not isinstance(hard_route_support, torch.Tensor):
                    raise RuntimeError("forward-routed measurement requires the actual hard route support")
                hard_route_support = hard_route_support.detach().to(device=route_coeff.device, dtype=torch.bool)
                measurement_support = hard_route_support
                if relative_default and bool(self.training) and bool(
                    getattr(self, "relative_support_coordinate_preservation", True)
                ):
                    if int(active_indices.numel()) != self.atom_count:
                        full_support = torch.zeros(self.atom_count, device=route_coeff.device, dtype=torch.bool)
                        full_support[active_indices] = hard_route_support
                    else:
                        full_support = hard_route_support
                    if bounded_magnitude is None or initial_support is None:
                        raise RuntimeError("relative-C dynamic route is missing cached forward primitives")
                    queued_support = full_support
        else:
            self._last_forward_routed_gate_enabled = False
            self._last_forward_routed_gate_alpha = float(getattr(self, "forward_routed_gate_alpha", 1.0))
            self._last_forward_routed_gate_active_atoms = float(self.atom_count)
            self._last_forward_routed_gate_active_ratio = 1.0
            self._last_forward_routed_gate_straight_through = False
            self._last_forward_routed_gate_ema_support = False
            self._last_forward_routed_gate_fixed_hard_support = False
            self._last_forward_routed_route_mass_skipped = False
            self._last_forward_routed_hard_gate = None
            self._last_forward_routed_soft_gate = None
            self._last_forward_routed_gate_support_jaccard = None
            self._last_forward_routed_pre_route_neff = None
            self._last_forward_routed_pre_route_mass95_atoms = None
            self._last_forward_routed_post_route_neff = None
            self._last_forward_routed_post_route_mass95_atoms = None

        if relative_default:
            if bounded_magnitude is None or initial_support is None:
                raise RuntimeError("relative-C forward magnitude was not materialized")
            if queued_support is not None:
                self.queue_relative_support_transition_(initial_support, queued_support)
                old_mean = self._masked_active_mean(bounded_magnitude, initial_support)
            else:
                old_mean = self._masked_active_mean(bounded_magnitude, initial_support)
            forward_code_full = self._relative_code_from_primitives(
                magnitude=bounded_magnitude,
                support_mask=initial_support,
                active_mean=old_mean,
            )
            full_coeff = self._effective_coefficient_from_code(forward_code_full)
        else:
            forward_code_full = self.quantized_coefficient_code(
                coefficient, support_mask=initial_support
            )
            full_coeff = self._effective_coefficient_from_code(forward_code_full)
        full_coeff = self._apply_effective_coefficient_contract(
            full_coeff, preserve_zero_support=True
        )
        coeff = full_coeff[active_indices]
        pure_code = forward_code_full[active_indices]

        weighted = projected * coeff
        if route_gate is not None:
            gate_view_shape = (*([1] * max(0, int(weighted.ndim) - 1)), int(route_gate.numel()))
            weighted = weighted * route_gate.reshape(gate_view_shape).to(device=weighted.device, dtype=weighted.dtype)
        if bool(getattr(self, "forward_solution_entropy_enabled", False)):
            if fixed_route_fast_mask is not None and self._forward_solution_entropy_uses_fixed_support_mask_metrics_only():
                self._record_forward_solution_fixed_support_metrics_from_mask(fixed_route_fast_mask)
            else:
                support_mask = self._record_forward_solution_entropy(
                    weighted=weighted, row_atoms=row_atoms, projected=projected
                )
                if support_mask is not None:
                    support_mask = support_mask.to(device=weighted.device, dtype=torch.bool)
                    measurement_support = measurement_support & support_mask
                    weighted = weighted * support_mask.to(device=weighted.device, dtype=weighted.dtype)
        self._record_activation_contribution_measurement_(
            weighted=weighted,
            row_atoms=row_atoms,
            active_indices=active_indices,
            support_mask=measurement_support,
            pure_coefficient_code=pure_code,
            route_gate=route_gate,
            projected=projected,
        )
        if (
            fixed_support_cache_used
            and fixed_route_fast_mask is not None
            and bool(getattr(self, "fixed_support_cache_output_parity_check", True))
            and not bool(getattr(self, "_fixed_support_cache_output_parity_checked", False))
        ):
            with torch.no_grad():
                fast_output = torch.matmul(weighted.detach(), row_atoms.detach().transpose(0, 1))
                reference_projected = torch.matmul(input_tensor.detach(), full_col_atoms.detach())
                reference_weighted = reference_projected * full_coeff.detach()
                reference_output = torch.matmul(
                    reference_weighted, full_row_atoms.detach().transpose(0, 1)
                )
                output_error = (fast_output.float() - reference_output.float()).abs()
                max_abs_error = output_error.amax()
                mean_abs_error = output_error.mean()
                reference_abs = reference_output.float().abs()
                max_relative_error = (output_error / reference_abs.clamp_min(1e-6)).amax()
                tolerance_value = float(getattr(self, "fixed_support_cache_output_parity_tolerance", 1e-6))
                allowed_max_error = tolerance_value * (1.0 + float(reference_abs.amax().detach().cpu()))
                max_abs_error_value = float(max_abs_error.detach().cpu())
                self._last_fixed_support_cache_output_parity_max_abs_error = max_abs_error.detach()
                self._last_fixed_support_cache_output_parity_mean_abs_error = mean_abs_error.detach()
                self._last_fixed_support_cache_output_parity_max_relative_error = max_relative_error.detach()
                self._fixed_support_cache_output_parity_checked = True
                if (
                    not bool(torch.isfinite(reference_output).all().detach().cpu())
                    or not bool(torch.isfinite(fast_output).all().detach().cpu())
                    or max_abs_error_value > allowed_max_error
                ):
                    # A cache parity failure must never poison the CUDA context.
                    # Record it, disable the fast path for this layer, and use the
                    # full reference computation from the current call onward.
                    reason = (
                        "nonfinite_output"
                        if not bool(torch.isfinite(fast_output).all().detach().cpu())
                        else "output_parity_tolerance"
                    )
                    self._disable_fixed_support_cache_(reason=reason)
                    weighted = reference_weighted.to(device=weighted.device, dtype=weighted.dtype)
                    row_atoms = full_row_atoms
                    active_indices = torch.arange(
                        self.atom_count, device=weighted.device, dtype=torch.long
                    )
                    measurement_support = self._actual_forward_support_mask_for_metrics(
                        device=weighted.device
                    )
        # release causal intervention: mask selected atom outputs only after
        # route/support resolution and cache parity checks. This preserves the
        # endpoint C, D, support and relative-C normalization while zeroing the
        # requested final rank-1 contributions for evaluation.
        intervention_output_mask = getattr(self, "_intervention_output_atom_mask", None)
        if isinstance(intervention_output_mask, torch.Tensor):
            full_mask = intervention_output_mask.to(device=weighted.device, dtype=weighted.dtype).reshape(-1)
            if int(full_mask.numel()) != int(self.atom_count):
                raise RuntimeError("intervention atom output mask length does not match atom_count")
            local_mask = full_mask.index_select(0, active_indices.to(device=weighted.device, dtype=torch.long))
            view_shape = (*([1] * max(0, int(weighted.ndim) - 1)), int(local_mask.numel()))
            weighted = weighted * local_mask.reshape(view_shape)
        output = torch.matmul(weighted, row_atoms.transpose(0, 1))
        return output

    def _record_forward_solution_entropy(
        self,
        *,
        weighted: torch.Tensor,
        row_atoms: torch.Tensor,
        projected: torch.Tensor | None = None,
    ) -> torch.Tensor | None:
        """Record actual forward contribution entropy and optional A1o support.

        Local mode preserves A1k/A1n behavior. Global-entmax mode uses the same
        per-sample contribution q but averages it across the current batch, then
        applies entmax-alpha. At alpha=2 this produces sparsemax-style support
        metrics; A1Q keeps hard support masks disabled, so support is recorded
        without removing atoms from the forward path.
        """

        mass_eps = float(getattr(self, "forward_solution_entropy_mass_eps", 1e-6))
        entropy_eps = float(getattr(self, "forward_solution_entropy_eps", 1e-8))
        mode = str(getattr(self, "forward_solution_entropy_mode", "local")).lower()
        alpha = float(getattr(self, "forward_solution_entmax_alpha", 1.0))
        row_norm = row_atoms.float().norm(dim=0).clamp_min(1e-8).detach()
        mass = torch.sqrt(weighted.float().pow(2) + mass_eps ** 2)
        row_norm = row_norm.to(device=mass.device, dtype=mass.dtype)
        mass = mass * row_norm
        metric_mass = mass
        mass = mass.reshape(-1, int(mass.shape[-1]))
        metric_mass = metric_mass.reshape(-1, int(metric_mass.shape[-1]))
        q = mass / mass.sum(dim=-1, keepdim=True).clamp_min(entropy_eps)
        metric_mass_detached = metric_mass.detach()
        metric_q = metric_mass_detached / metric_mass_detached.sum(dim=-1, keepdim=True).clamp_min(entropy_eps)
        h_raw = -(q * q.clamp_min(entropy_eps).log()).sum(dim=-1)
        h_norm = h_raw / math.log(max(2, int(self.atom_count)))
        metric_h_raw = -(metric_q * metric_q.clamp_min(entropy_eps).log()).sum(dim=-1)
        metric_h_norm = metric_h_raw / math.log(max(2, int(self.atom_count)))
        support_mask: torch.Tensor | None = None
        record_metrics = bool(getattr(self, "forward_solution_entropy_record_metrics", True))
        used_atom_entropy = None
        if record_metrics:
            usage_weight = q.detach().mean(dim=0)
            atom_entropy = _dictionary_entropy_ratio_per_atom(self).to(device=usage_weight.device, dtype=usage_weight.dtype)
            used_atom_entropy = (usage_weight * atom_entropy).sum()
        if mode in {"global_entmax", "global_sparsemax", "a1o_global_entmax"}:
            r = q.mean(dim=0)
            entmax_distribution = _entmax_alpha_1d((r + entropy_eps).log(), alpha)
            entmax_distribution = entmax_distribution.to(device=r.device, dtype=r.dtype)
            global_entropy_raw = -(entmax_distribution * entmax_distribution.clamp_min(entropy_eps).log()).sum()
            global_entropy_norm = global_entropy_raw / math.log(max(2, int(self.atom_count)))
            tolerance = float(getattr(self, "forward_solution_support_tolerance", 1e-12))
            with torch.no_grad():
                support_source = (
                    self.global_solution_usage_ema.to(device=r.device, dtype=r.dtype)
                    if bool(getattr(self, "forward_solution_use_ema_support", True))
                    and self._global_solution_usage_ema_is_initialized()
                    else r.detach()
                )
                support_distribution = _entmax_alpha_1d((support_source + entropy_eps).log(), alpha).to(device=r.device, dtype=r.dtype)
                support_mask = support_distribution.detach() > tolerance
                # Numerical/tolerance guard without host sync: the max-usage atom
                # is always allowed, which is a no-op for a normal sparsemax
                # distribution but prevents an all-false mask if a caller sets a
                # very aggressive tolerance.
                support_mask = support_mask | F.one_hot(
                    torch.argmax(support_source.detach()).reshape(()),
                    num_classes=int(support_mask.numel()),
                ).to(device=support_mask.device, dtype=torch.bool)
                active_count_value: float | None = None
                if record_metrics:
                    active_count_value = float(support_mask.detach().float().sum().cpu())
                support_mask = None
            if record_metrics:
                with torch.no_grad():
                    active_count = float(active_count_value if active_count_value is not None else int(self.atom_count))
                    self._last_global_solution_entropy = float(global_entropy_norm.detach().cpu())
                    self._last_global_solution_neff_atoms = float(torch.exp(global_entropy_raw.detach()).cpu())
                    self._last_global_solution_support_active_atoms = active_count
                    self._last_global_solution_support_inactive_atoms = float(max(0.0, float(self.atom_count) - active_count))
                    self._last_global_solution_entmax_alpha = float(alpha)
        if record_metrics:
            with torch.no_grad():
                metric_neff = torch.exp(metric_h_raw.detach())
                loss_neff = torch.exp(h_raw.detach())
                self._last_forward_solution_entropy_mean = float(metric_h_norm.detach().mean().cpu())
                self._last_forward_solution_entropy_p95 = _tensor_quantile_float(metric_h_norm.detach().flatten(), 0.95)
                self._last_forward_solution_neff_mean = float(metric_neff.mean().cpu())
                self._last_forward_solution_neff_p95 = _tensor_quantile_float(metric_neff.flatten(), 0.95)
                mass95_mean, mass95_p95 = _mass95_atoms_from_sample_distribution(metric_q.detach(), mass_target=0.95)
                self._last_forward_solution_mass95_atoms_mean = mass95_mean
                self._last_forward_solution_mass95_atoms_p95 = mass95_p95
                self._last_forward_solution_loss_mass_entropy_mean = float(h_norm.detach().mean().cpu())
                self._last_forward_solution_loss_mass_entropy_p95 = _tensor_quantile_float(h_norm.detach().flatten(), 0.95)
                self._last_forward_solution_loss_mass_neff_mean = float(loss_neff.mean().cpu())
                self._last_forward_solution_loss_mass_neff_p95 = _tensor_quantile_float(loss_neff.flatten(), 0.95)
                loss_mass95_mean, loss_mass95_p95 = _mass95_atoms_from_sample_distribution(q.detach(), mass_target=0.95)
                self._last_forward_solution_loss_mass_mass95_atoms_mean = loss_mass95_mean
                self._last_forward_solution_loss_mass_mass95_atoms_p95 = loss_mass95_p95
                self._last_forward_solution_used_atom_entropy = float((used_atom_entropy if used_atom_entropy is not None else h_norm.new_zeros(())).detach().cpu())
                if mode not in {"global_entmax", "global_sparsemax", "a1o_global_entmax"}:
                    self._last_global_solution_entropy = 0.0
                    self._last_global_solution_neff_atoms = 0.0
                    self._last_global_solution_support_active_atoms = float(self.atom_count)
                    self._last_global_solution_support_inactive_atoms = 0.0
                    self._last_global_solution_entmax_alpha = float(alpha)
                    return None

    def forward(self, input_tensor: torch.Tensor) -> torch.Tensor:
        output = self.dictionary_linear(input_tensor, self.coefficient_magnitude)
        if self.bias is not None:
            output = output + self.bias
        return output

    @torch.no_grad()

    # --- Post-step maintenance and report metrics ----------------------------
    def rescale_coefficients_to_target_rms(self, *, calibrate_dictionary_base: bool = False) -> None:
        """Rescale active coefficients to the initialization RMS without materializing W.

        The exact Frobenius norm of ``sum_k c_k outer(r_k, q_k)`` is
        ``c^T ((R^T R) * (Q^T Q)) c``. After hard top-k projection this
        computes over only active coefficients, avoiding dense FFN weight
        reconstruction on every optimizer step.
        """

        coeff = self.coefficient_magnitude
        effective_coeff = self.effective_coefficient().detach()
        active_mask = effective_coeff.abs() > 0.0
        if not bool(active_mask.any()):
            return
        row_atoms, col_atoms = self._row_and_col_atoms()
        active_coeff = effective_coeff[active_mask].float()
        active_rows = row_atoms.detach()[:, active_mask].float()
        active_cols = col_atoms.detach()[:, active_mask].float()
        gram = torch.matmul(active_rows.transpose(0, 1), active_rows) * torch.matmul(
            active_cols.transpose(0, 1), active_cols
        )
        frobenius_sq = torch.dot(active_coeff, torch.matmul(gram.to(active_coeff.device), active_coeff)).clamp_min(1e-24)
        current_rms = float((frobenius_sq / float(max(1, self.out_features * self.in_features))).sqrt().cpu())
        rescale = self.target_weight_rms / max(1e-12, current_rms)
        if bool(getattr(self, "relative_coefficient_enabled", False)):
            if not math.isfinite(rescale) or rescale <= 0.0:
                raise RuntimeError(f"relative-C dictionary scale calibration produced invalid rescale={rescale!r}")
            log_rescale = math.log(float(rescale))
            if bool(getattr(self, "dictionary_local_scale_enabled", False)):
                self.dictionary_log_scale.add_(log_rescale)
            else:
                # Attention Q/K/V/O use shared trainable functional scales. A
                # fixed per-operator coordinate factor is allowed only for exact initial
                # calibration and support-coordinate preservation.
                self.relative_coordinate_log_scale.add_(log_rescale)
        elif bool(getattr(self, "coefficient_quantization_enabled", False)):
            if hasattr(self, "dictionary_log_scale"):
                self.dictionary_log_scale.add_(math.log(max(1e-24, float(rescale))))
            else:
                self.coefficient_magnitude.mul_(rescale)
        else:
            self.coefficient_magnitude.mul_(rescale)

    @torch.no_grad()
    def renormalize_atoms(self) -> None:
        self.row_atoms.copy_(_column_normalize(self.row_atoms))
        self.col_atoms.copy_(_column_normalize(self.col_atoms))


    @torch.no_grad()
    def enforce_committed_sparse_support(self, *, enforce_coefficients: bool = True) -> None:
        """Keep final/prior sparse supports fixed during committed fine-tuning."""

        active_coefficient = self.coefficient_magnitude
        if enforce_coefficients and self.coefficient_support_is_committed():
            active_coefficient.masked_fill_(~self.coefficient_commit_mask.to(active_coefficient.device), 0.0)

    @torch.no_grad()
    def raw_relative_c_concentration_metrics(self) -> dict[str, float | str]:
        """Return lightweight raw-C concentration metrics for one layer.

        This path intentionally avoids dictionary norms, activation evaluation,
        pairwise contribution metrics, and per-batch logging. It is called once
        at each epoch boundary so short-lived Target concentration at C=8 is not
        hidden by the sparse evaluation schedule.
        """

        active_coefficient = self.coefficient_magnitude
        support_mask = self._actual_forward_support_mask_for_metrics(device=active_coefficient.device)
        bounded_magnitude = self._bounded_relative_magnitude(detach=True).to(
            device=active_coefficient.device
        ).float()
        active_indices = torch.nonzero(support_mask, as_tuple=False).flatten()
        active_magnitude = bounded_magnitude[support_mask]
        tolerance = max(1e-6, float(getattr(self, "relative_coefficient_measurement_tolerance", 1e-3)))
        if int(active_magnitude.numel()) <= 0:
            return {
                "relative_c_actual_support_atom_count": 0.0,
                "relative_c_raw_active_min": 0.0,
                "relative_c_raw_active_mean": 0.0,
                "relative_c_raw_active_max": 0.0,
                "relative_c_raw_max_min_ratio": 0.0,
                "relative_c_raw_near_min_atom_ratio": 0.0,
                "relative_c_raw_near_max_atom_ratio": 0.0,
                "relative_c_raw_top1_share": 0.0,
                "relative_c_raw_top5_share": 0.0,
                "relative_c_raw_top5_atom_indices": "",
                "relative_c_raw_top5_values": "",
            }
        # One epoch-boundary device transfer per tensor avoids repeated CUDA
        # synchronizations while keeping the normal training hot path untouched.
        active_magnitude_cpu = active_magnitude.detach().float().cpu()
        active_indices_cpu = active_indices.detach().cpu()
        top_count = min(5, int(active_magnitude_cpu.numel()))
        top_values, top_positions = torch.topk(active_magnitude_cpu, k=top_count)
        top_indices = active_indices_cpu[top_positions]
        total = active_magnitude_cpu.sum().clamp_min(1e-12)
        active_min = active_magnitude_cpu.min()
        active_max = active_magnitude_cpu.max()
        return {
            "relative_c_actual_support_atom_count": float(active_magnitude_cpu.numel()),
            "relative_c_raw_active_min": float(active_min),
            "relative_c_raw_active_mean": float(active_magnitude_cpu.mean()),
            "relative_c_raw_active_max": float(active_max),
            "relative_c_raw_max_min_ratio": float(active_max / active_min.clamp_min(1e-12)),
            "relative_c_raw_near_min_atom_ratio": float(
                (active_magnitude_cpu <= float(self.relative_coefficient_min_ratio) + tolerance).float().mean()
            ),
            "relative_c_raw_near_max_atom_ratio": float(
                (active_magnitude_cpu >= float(self.relative_coefficient_max_ratio) - tolerance).float().mean()
            ),
            "relative_c_raw_top1_share": float(top_values[0] / total),
            "relative_c_raw_top5_share": float(top_values.sum() / total),
            "relative_c_raw_top5_atom_indices": ";".join(str(int(value)) for value in top_indices.tolist()),
            "relative_c_raw_top5_values": ";".join(f"{float(value):.8g}" for value in top_values.tolist()),
        }

