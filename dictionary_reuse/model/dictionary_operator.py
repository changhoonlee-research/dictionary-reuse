    @torch.no_grad()
    def _update_forward_routed_usage_ema_(
        self,
        route_state: torch.Tensor,
        *,
        residual_route_mode: bool,
        ema_initialized: bool,
    ) -> bool:
        """Update route EMA while preserving Condition-C protected entries exactly.

        In coefficient-contract residual mode only inactive/trainable atoms belong to the
        residual route process. Protected A-active EMA entries are therefore
        immutable endpoint state and must not decay merely because their route
        mass is excluded from the residual candidate vector.
        """

        ema = self.global_solution_usage_ema
        state = route_state.detach().to(device=ema.device, dtype=ema.dtype)
        if int(state.numel()) != int(ema.numel()):
            raise RuntimeError(
                "forward-routed EMA state length does not match dictionary atom count"
            )
        if residual_route_mode:
            trainable = self._route_trainable_mask.to(
                device=ema.device, dtype=torch.bool
            ).reshape(-1)
            if int(trainable.numel()) != int(ema.numel()):
                raise RuntimeError(
                    "coefficient-contract route-trainable mask length does not match atom_count"
                )
            selected_state = state.masked_select(trainable)
            if not ema_initialized:
                if int(selected_state.numel()) > 0:
                    ema.masked_scatter_(trainable, selected_state)
                self._set_global_solution_usage_ema_initialized(True)
                return True
            if int(selected_state.numel()) > 0:
                decay = max(
                    0.0,
                    min(
                        0.9999,
                        float(getattr(self, "forward_solution_usage_ema_decay", 0.95)),
                    ),
                )
                selected_ema = ema.masked_select(trainable)
                ema.masked_scatter_(
                    trainable,
                    selected_ema.mul(decay).add(selected_state, alpha=1.0 - decay),
                )
            return True

        if not ema_initialized:
            ema.copy_(state)
            self._set_global_solution_usage_ema_initialized(True)
            return True
        decay = max(
            0.0,
            min(0.9999, float(getattr(self, "forward_solution_usage_ema_decay", 0.95))),
        )
        ema.mul_(decay).add_(state, alpha=1.0 - decay)
        return True

