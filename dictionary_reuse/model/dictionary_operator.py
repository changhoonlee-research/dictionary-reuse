    def _disable_fixed_support_cache_(self, *, reason: str) -> None:
        if not bool(getattr(self, "_fixed_support_cache_disabled", False)):
            self._fixed_support_cache_fallback_count = int(
                getattr(self, "_fixed_support_cache_fallback_count", 0)
            ) + 1
        self._fixed_support_cache_disabled = True
        self._fixed_support_cache_fallback_reason = str(reason)
        self._fixed_support_active_atom_cache = None

    def _fixed_support_active_atoms(
        self,
        *,
        active: torch.Tensor,
        row_atoms: torch.Tensor,
        col_atoms: torch.Tensor,
        coefficient: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        """Cache only immutable active indices; always gather current D and C.

        Caching row/column slices can resurrect stale atoms after a freeze/train/
        freeze transition. Index-only caching preserves the speed benefit that is
        safe for both Source and Target while always reading current parameters.
        """

        if bool(getattr(self, "_fixed_support_cache_disabled", False)):
            indices = torch.nonzero(active, as_tuple=False).reshape(-1)
        else:
            cache = self._fixed_support_active_atom_cache
            key = (
                str(row_atoms.device),
                str(row_atoms.dtype),
                str(coefficient.dtype),
                int(getattr(self, "_fixed_support_cache_version", 0)),
                int(active.numel()),
            )
            if cache is None or cache.get("key") != key:
                indices = torch.nonzero(active, as_tuple=False).reshape(-1)
                if int(indices.numel()) <= 0:
                    raise RuntimeError("fixed-support active-atom cache requires nonempty support")
                cache = {
                    "key": key,
                    "indices": indices,
                    "support_active_count": int(indices.numel()),
                    "row_atoms": None,
                    "col_atoms": None,
                }
                self._fixed_support_active_atom_cache = cache
            else:
                indices = cache["indices"]
        if int(indices.numel()) <= 0:
            raise RuntimeError("fixed-support path requires nonempty support")
        return (
            indices,
            coefficient.index_select(0, indices),
            row_atoms.index_select(1, indices),
            col_atoms.index_select(1, indices),
        )

