    # --- Initialization and serialized runtime state -------------------------
    def _initialize_coefficient_magnitude(self, quantization_config: Mapping[str, Any], *, seed: int) -> None:
        """Initialize the direct positive coefficient magnitude in [1, 8]."""

        init_config = quantization_config.get("magnitude_init", {})
        if not isinstance(init_config, Mapping):
            init_config = {}
        init_type = str(init_config.get("type", "ones")).lower()
        init_seed = int(
            init_config.get(
                "seed",
                quantization_config.get(
                    "magnitude_init_seed",
                    quantization_config.get("coefficient_magnitude_init_seed", int(seed) + 1009),
                ),
            )
        )
        self.coefficient_magnitude_init_seed = init_seed
        generator = torch.Generator(device="cpu")
        generator.manual_seed(init_seed)

        def store(values: torch.Tensor) -> None:
            if not bool(torch.isfinite(values).all()) or not bool((values > 0.0).all()):
                raise ValueError("coefficient magnitude initialization values must be positive and finite")
            minimum = float(self.relative_coefficient_min_ratio) if self.relative_coefficient_enabled else float(self.coefficient_quantization_min_abs)
            maximum = float(self.relative_coefficient_max_ratio) if self.relative_coefficient_enabled else float(self.coefficient_quantization_max_abs)
            self.coefficient_magnitude.copy_(values.clamp(min=minimum, max=maximum))

        if init_type in {"uniform", "uniform_abs"}:
            low = float(init_config.get("low", 1.0))
            high = float(init_config.get("high", 1.5))
            if not math.isfinite(low) or not math.isfinite(high) or high < low or low <= 0.0:
                raise ValueError(f"Invalid magnitude uniform init range low={low!r}, high={high!r}")
            values = torch.empty(self.atom_count, dtype=torch.float32)
            values.uniform_(low, high, generator=generator)
            store(values)
            return
        if init_type in {"categorical", "discrete"}:
            values = init_config.get("values", [1.0])
            probs = init_config.get("probs", [1.0])
            if not isinstance(values, Sequence) or not isinstance(probs, Sequence) or len(values) != len(probs) or not values:
                raise ValueError("categorical magnitude_init requires nonempty equal-length values and probs")
            value_tensor = torch.tensor([float(value) for value in values], dtype=torch.float32)
            prob_tensor = torch.tensor([float(prob) for prob in probs], dtype=torch.float32)
            if (
                not bool(torch.isfinite(value_tensor).all())
                or not bool((value_tensor > 0.0).all())
                or not bool(torch.isfinite(prob_tensor).all())
                or float(prob_tensor.sum()) <= 0.0
            ):
                raise ValueError("categorical magnitude_init values must be positive and probs must have positive finite mass")
            prob_tensor = prob_tensor.clamp_min(0.0)
            prob_tensor = prob_tensor / prob_tensor.sum().clamp_min(1e-12)
            sample = torch.multinomial(prob_tensor, num_samples=self.atom_count, replacement=True, generator=generator)
            store(value_tensor[sample])
            return
        store(torch.ones(self.atom_count, dtype=torch.float32))

    def _load_from_state_dict(
        self,
        state_dict: Mapping[str, Any],
        prefix: str,
        local_metadata: Mapping[str, Any],
        strict: bool,
        missing_keys: list[str],
        unexpected_keys: list[str],
        error_msgs: list[str],
    ) -> None:
        """Load the current DiR state schema and refresh runtime caches."""

        super()._load_from_state_dict(
            state_dict,
            prefix,
            local_metadata,
            strict,
            missing_keys,
            unexpected_keys,
            error_msgs,
        )
        self._sync_cached_boolean_buffers_from_tensors()

    def _sync_cached_boolean_buffers_from_tensors(self) -> None:
        # This is called only after state copies/load-state operations, not from
        # normal forward paths. A one-time CPU read here is acceptable and keeps
        # runtime branches host-sync-free.
        self._coefficient_support_committed_cached = bool(self.coefficient_support_committed.detach().to(device="cpu").item())
        self._global_solution_usage_ema_initialized_cached = bool(self.global_solution_usage_ema_initialized.detach().to(device="cpu").item())
        self._forward_routed_fixed_support_initialized_cached = bool(self.forward_routed_fixed_support_initialized.detach().to(device="cpu").item())
        contract_mode_code = int(
            self._coefficient_contract_mode_code.detach().to(device="cpu").item()
        )
        contract_modes = {0: "none", 1: "bounded", 2: "frozen"}
        if contract_mode_code not in contract_modes:
            raise RuntimeError(f"Invalid persistent coefficient-contract contract mode code: {contract_mode_code}")
        self._coefficient_contract_mode = contract_modes[contract_mode_code]
        self._residual_route_enabled_cached = bool(
            self._residual_route_enabled.detach().to(device="cpu").item()
        )
        self._invalidate_fixed_support_metric_caches()

    def _invalidate_fixed_support_route_metric_cache(self) -> None:
        self._fixed_support_route_metrics_cache = None

